local Assert = require("tests.assert")
local State = require("kiwi.terminal.state")
local Utf8 = require("kiwi.terminal.utf8")
local Search = require("kiwi.input.search")
local Terminal = require("kiwi.session.terminal")
local Transaction = require("kiwi.terminal.state_transaction")
local function complete(state, budget)
  local ticks, match, status = 0
  repeat
    match, status = state:search_step(budget)
    Assert.truthy(state.search.last_step_work <= (budget or Search.step_budget))
    ticks = ticks + 1
    assert(ticks < 100000, "search did not terminate")
  until not state:search_pending()
  return match, status, ticks
end

local function write_row(state, row, codepoints)
  state:set_cursor(0, row)
  for _, codepoint in ipairs(codepoints) do
    state:write_codepoint(Utf8.encode(codepoint), codepoint)
  end
end

return {
  regex_search_joins_soft_wraps_and_maps_combining_and_wide_cells = function()
    local terminal = Terminal.new({ columns = 5, rows = 3 })
    terminal:write("pre中épost")
    local state = Terminal.state(terminal)
    state:search_begin("forward", "regex")
    state:search_append("中ép")
    local match, status = state:search_submit()
    if status == "searching" then match, status = complete(state, 3) end
    Assert.equal(status, "matches")
    Assert.equal(match.row_index, 1); Assert.equal(match.finish_row_index, 2)
    Assert.equal(match.start_column, 3); Assert.equal(match.finish_column, 2)
    Assert.truthy(match.line_id ~= match.finish_line_id)
    local descriptor = require("kiwi.renderer.search").descriptor(state)
    Assert.equal(descriptor.start_row, 0); Assert.equal(descriptor.finish_row, 1)
    Assert.truthy(descriptor.active)
  end,
  regex_anchors_ignore_erased_padding_and_preserve_explicit_spaces = function()
    local terminal = Terminal.new({ columns = 12, rows = 3 })
    terminal:write("cat\r\ncat ")
    local state = Terminal.state(terminal)
    state:search_begin("forward", "regex"); state:search_append("^cat$")
    local match, status = state:search_submit()
    Assert.equal(status, "matches"); Assert.equal(state:search_view().match_count, 1)
    Assert.equal(match.row_index, 1)
    state:search_begin("forward", "regex"); state:search_append("^cat $")
    match, status = state:search_submit()
    Assert.equal(status, "matches"); Assert.equal(match.row_index, 2)
    state:search_begin("forward", "regex"); state:search_append("^$")
    match, status = state:search_submit()
    Assert.equal(status, "matches"); Assert.equal(match.row_index, 3)
    Assert.truthy(match.empty)
    local descriptor = require("kiwi.renderer.search").descriptor(state)
    Assert.equal(descriptor.start_column, 0); Assert.equal(descriptor.finish_column, 1)
  end,
  search_jobs_yield_cancel_and_invalidate_without_retaining_documents = function()
    local state = State.new(120, 80)
    state:search_begin("forward", "regex"); state:search_append("needle")
    local _, status = state:search_submit()
    Assert.equal(status, "searching"); Assert.truthy(state:search_pending())
    local work = state.search.work
    state:search_step(1)
    Assert.truthy(state.search.work > work); Assert.equal(state.search.last_step_work, 1)
    state:clear_search(); Assert.equal(state:search_pending(), false)
    Assert.equal(state:search_view().status, "inactive")
    state:search_begin("forward"); state:search_append("needle"); state:search_submit()
    state:write_codepoint("n", 110)
    Assert.equal(state:search_pending(), false)
    Assert.equal(state:search_view().status, "stale")
    Assert.equal(state:search_view().match_count, 0)
  end,
  search_limits_are_visible_and_partial_matches_remain_navigable = function()
    local terminal = Terminal.new({ columns = 20, rows = 1 }); terminal:write("aaaaa")
    local state = Terminal.state(terminal)
    state.search = Search.new({ maximum_matches = 2 })
    state:search_begin("forward", "regex"); state:search_append("a")
    local match, status = state:search_submit()
    Assert.equal(status, "match-limit"); Assert.truthy(state:search_view().truncated)
    Assert.equal(match.start_column, 0)
    match, status = state:search_navigate("forward")
    Assert.equal(status, "match-limit"); Assert.equal(match.start_column, 1)
    state.search = Search.new({ maximum_work = 10 })
    state:search_begin("forward"); state:search_append("z")
    Assert.equal(select(2, state:search_submit()), "work-limit")
    Assert.equal(state.search.work, 10); Assert.equal(state:search_pending(), false)
    state.search = Search.new({ maximum_line_points = 4 })
    state:search_begin("forward"); state:search_append("z")
    Assert.equal(select(2, state:search_submit()), "line-limit")
  end,
  invalid_regex_stays_editable_and_literal_mode_does_not_interpret_syntax = function()
    local terminal = Terminal.new({ columns = 20, rows = 1 }); terminal:write("[x]+")
    local state = Terminal.state(terminal)
    state:search_begin("forward", "regex"); state:search_append("[")
    Assert.equal(select(2, state:search_submit()), "invalid-pattern")
    Assert.truthy(state:search_view().editing)
    Assert.truthy(Search.title(state:search_view(), "Kiwi"):find("unclosed", 1, true))
    state:search_toggle_mode(); state:search_append("x]+")
    local match, status = state:search_submit()
    Assert.equal(status, "matches"); Assert.equal(match.finish_column, 4)
    Assert.equal(state:search_view().mode, "literal")
  end,
  pending_search_jobs_survive_transaction_copy_without_mutating_the_live_job = function()
    local state = State.new(100, 60)
    state:set_cursor(0, 59); state:write_codepoint("z", 122)
    state:search_begin("forward", "regex"); state:search_append("z$")
    Assert.equal(select(2, state:search_submit()), "searching")
    local original_work = state.search.work
    local transaction = Transaction.new(state, { columns = 100, rows = 60 })
    local match, status = complete(transaction.state, 127)
    Assert.equal(status, "matches"); Assert.equal(match.row_index, 60)
    Assert.equal(state.search.work, original_work); Assert.truthy(state:search_pending())
    transaction:seal(); transaction:commit()
    Assert.equal(state:search_view().status, "matches")
    Assert.equal(state:search_pending(), false)
  end,
  search_maps_unicode_matches_to_whole_grapheme_cells = function()
    local state = State.new(5, 2)
    write_row(state, 0, { 0x61, 0x4e2d, 0x62 })
    write_row(state, 1, { 0x4e2d, 0x61 })
    state:search_begin("forward")
    Assert.truthy(state:search_append("中"))
    local match, status = state:search_submit("forward")
    Assert.equal(status, "matches")
    Assert.equal(match.start_column, 1)
    Assert.equal(match.finish_column, 3)
    match, status = state:search_navigate("forward")
    Assert.equal(status, "matches")
    Assert.equal(match.start_column, 0)
    Assert.equal(match.finish_column, 2)
    match = state:search_navigate("backward")
    Assert.equal(match.start_column, 1)
  end,

  search_reveals_retained_history_without_changing_selection = function()
    local state = State.new(3, 2)
    write_row(state, 0, { 0x6f, 0x6c, 0x64 })
    state:set_selection(1, 0, 1, 1)
    local selection = state:selection_view()
    state:scroll_up(1)
    write_row(state, 1, { 0x6e, 0x65, 0x77 })
    state:search_begin("forward")
    Assert.truthy(state:search_append("old"))
    local match = state:search_submit("forward")
    Assert.equal(match.start_column, 0)
    Assert.equal(state.history_offset, 1)
    local after = state:selection_view()
    Assert.equal(after.anchor.line_id, selection.anchor.line_id)
    Assert.equal(after.focus.line_id, selection.focus.line_id)
  end,

  search_reports_empty_no_match_and_stale_documents = function()
    local state = State.new(4, 1)
    write_row(state, 0, { 0x61, 0x61, 0x61, 0x61 })
    state:search_begin("forward")
    local match, status = state:search_submit("forward")
    Assert.equal(match, nil)
    Assert.equal(status, "empty")
    state:search_begin("forward")
    Assert.truthy(state:search_append("zz"))
    match, status = state:search_submit("forward")
    Assert.equal(match, nil)
    Assert.equal(status, "no-match")
    state:search_begin("forward")
    Assert.truthy(state:search_append("aa"))
    match, status = state:search_submit("forward")
    Assert.equal(status, "matches")
    Assert.equal(state:search_view().match_count, 3)
    match, status = state:search_navigate("forward")
    Assert.equal(status, "matches")
    Assert.equal(match.start_column, 1)
    state:set_cursor(0, 0)
    state:write_codepoint("b", 0x62)
    match, status = state:search_navigate("forward")
    Assert.equal(match, nil)
    Assert.equal(status, "stale")
    Assert.equal(state:search_view().status, "stale")
  end,
}
