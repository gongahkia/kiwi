local Assert = require("tests.assert")
local Terminal = require("kiwi.session.terminal")

return {
  select_all_includes_history_and_copies_unicode_without_soft_wrap_newlines = function()
    local terminal = Terminal.new({ columns = 5, rows = 2 })
    terminal:write("abcdefgh\r\n中x")
    local state = Terminal.state(terminal)
    Assert.truthy(state.scrollback:size() > 0)
    state:select_all()
    Assert.equal(state:selection_text(100), "abcdefgh\n中x")
    local text, reason = state:selection_text(4)
    Assert.equal(text, nil)
    Assert.equal(reason, "over-limit")
  end,
  clear_scrollback_keeps_live_cells_and_cursor_and_invalidates_old_matches = function()
    local terminal = Terminal.new({ columns = 8, rows = 2 })
    terminal:write("old\r\nlive\r\ncurrent")
    local state = Terminal.state(terminal)
    state:search_begin("forward")
    state:search_append("old")
    Assert.truthy(state:search_submit("forward"))
    state:select_all()
    local cursor = state.active_screen.cursor
    local column, row = cursor.column, cursor.row
    terminal:write("\27[3J")
    Assert.equal(state.scrollback:size(), 0)
    Assert.equal(state.history_offset, 0)
    Assert.equal(cursor.column, column)
    Assert.equal(cursor.row, row)
    Assert.equal(state:get(0, 0).glyph, "l")
    Assert.equal(state:get(0, 1).glyph, "c")
    Assert.equal(state:selection_view().active, false)
    Assert.equal(state:search_view().status, "stale")
    state:select_all()
    Assert.equal(state:selection_text(100), "live\ncurrent")
  end,
  history_actions_do_not_erase_primary_history_from_the_alternate_screen = function()
    local terminal = Terminal.new({ columns = 8, rows = 2 })
    terminal:write("old\r\nlive\r\ncurrent\27[?1049hALT")
    local state = Terminal.state(terminal)
    local retained = state.scrollback:size()
    state:select_all()
    Assert.equal(state:selection_text(100), "ALT\n")
    Assert.equal(state:clear_scrollback(), false)
    terminal:write("\27[3J")
    Assert.equal(state:get(0, 0).glyph, "A")
    Assert.equal(state.scrollback:size(), retained)
    terminal:write("\27[?1049l")
    Assert.equal(state:get(0, 1).glyph, "c")
  end,
}
