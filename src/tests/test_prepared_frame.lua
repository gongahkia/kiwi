local Assert = require("tests.assert")
local PreparedFrame = require("kiwi.renderer.prepared_frame")
local State = require("kiwi.terminal.state")
local System = require("kiwi.font.system")

local function text_system()
  return System.new({ pixel_height = 18, atlas = { width = 512, height = 512, max_entries = 1024 } })
end

return {
  block_selection_packs_per_cell_geometry_and_a_separate_vi_cursor = function()
    local bit = require("bit")
    local Packing = require("kiwi.renderer.packing")
    local font = text_system()
    local state = State.new(8, 2)
    state:write_codepoint("a"); state:write_codepoint("中", 0x4e2d)
    local app_column = state.cursor.column
    state:vi_toggle(); state.vi:motion(state, "first"); state.vi:motion(state, "right")
    state.vi:toggle_selection(state, "block")
    local prepared = PreparedFrame.new(font, state)
    local plan = prepared:prepare_model(state)
    Assert.equal(bit.band(tonumber(prepared.cells[1].flags), Packing.wide_cell), Packing.wide_cell)
    Assert.equal(bit.band(tonumber(prepared.cells[2].flags), Packing.continuation_cell), Packing.continuation_cell)
    local frame = prepared:prepare_frame(state, 1, false, false)
    Assert.equal(frame.data[0].command_region_padding[2], 1)
    Assert.truthy(frame.selection.block)
    Assert.equal(frame.cursor.column, 1); Assert.equal(frame.cursor.blink, false)
    Assert.equal(state.cursor.column, app_column)
    prepared:commit_model(plan)
    state.vi:cancel(state)
    Assert.equal(prepared:prepare_frame(state, 2, false, false).data[0].command_region_padding[2], 0)
    prepared:destroy(); font:destroy()
  end,
  prepared_frames_preserve_other_pane_pixels_and_upload_reclaimed_slots = function()
    local font = System.new({ pixel_height = 18, atlas = { width = 128, height = 128, max_entries = 2 } })
    local a, b = State.new(2, 1), State.new(2, 1)
    a:write_codepoint("A")
    b:write_codepoint("B")
    local first, second = PreparedFrame.new(font, a), PreparedFrame.new(font, b)
    first:commit_model(first:prepare_model(a))
    second:commit_model(second:prepare_model(b))
    local stable_u, stable_v = tonumber(first.glyphs[0].u0), tonumber(first.glyphs[0].v0)
    b:set_cursor(0, 0)
    b:write_codepoint("C")
    local changed = second:prepare_model(b)
    Assert.truthy(changed.atlas_update)
    Assert.equal(tonumber(changed.glyph_update.data[0].glyph), font.primary:glyph_index(string.byte("C")))
    second:discard_model(changed)
    local retry = second:prepare_model(b)
    Assert.truthy(retry.atlas_update)
    Assert.truthy(retry.glyph_update)
    second:commit_model(retry)
    local unchanged = first:prepare_model(a)
    Assert.equal(unchanged.glyph_update, nil)
    Assert.equal(tonumber(first.glyphs[0].u0), stable_u)
    Assert.equal(tonumber(first.glyphs[0].v0), stable_v)
    Assert.equal(tonumber(first.glyphs[0].glyph), font.primary:glyph_index(string.byte("A")))
    first:commit_model(unchanged)
    first:destroy()
    second:destroy()
    Assert.equal(next(font.glyph_cache.owner_glyphs), nil)
    font:destroy()
  end,
  prepared_frame_keeps_terminal_updates_pending_until_a_backend_acknowledges_them = function()
    local font = text_system()
    local state = State.new(8, 2)
    state:write_codepoint("K")
    local prepared = PreparedFrame.new(font, state)
    local plan = prepared:prepare_model(state)
    Assert.equal(plan.revision, 1)
    Assert.equal(#plan.cell_updates, 1)
    Assert.truthy(plan.cell_updates[1].data ~= nil)
    Assert.truthy(plan.glyph_update ~= nil)
    Assert.truthy(plan.atlas_update ~= nil)
    Assert.truthy(state.damage.dirty_count > 0)
    Assert.equal(plan.descriptors.cursor.column, state.cursor.column)
    prepared:commit_model(plan)
    Assert.equal(state.damage.dirty_count, 0)
    Assert.equal(prepared.glyph_count, plan.glyph_update.count)
    Assert.equal(prepared.atlas_generation, plan.atlas_update.generation)
    prepared:destroy()
    font:destroy()
  end,
  prepared_frame_builds_backend_neutral_uniform_data = function()
    local font = text_system()
    local state = State.new(8, 2)
    local prepared = PreparedFrame.new(font, state, { command_region_visual_enabled = true })
    local frame = prepared:prepare_frame(state, 12.5, true, false, { surface_is_srgb = true })
    Assert.equal(frame.byte_count, 736)
    Assert.equal(frame.time, 12.5)
    Assert.equal(frame.delta, 12.5)
    Assert.equal(frame.data[0].columns, 8)
    Assert.equal(frame.data[0].rows, 2)
    Assert.equal(frame.data[0].show_dirty, 1)
    Assert.equal(frame.data[0].show_boundaries, 0)
    Assert.equal(frame.data[0].command_region_padding[0], 1)
    Assert.equal(frame.data[0].scrollbar_visible, 0)
    prepared:destroy()
    font:destroy()
  end,
  prepared_frame_retries_a_discarded_upload_as_a_complete_resource_snapshot = function()
    local font = text_system()
    local state = State.new(8, 2)
    local prepared = PreparedFrame.new(font, state)
    local initial = prepared:prepare_model(state)
    prepared:discard_model(initial)
    Assert.truthy(state.damage.dirty_count > 0)
    local retry = prepared:prepare_model(state)
    Assert.equal(#retry.cell_updates, 1)
    Assert.equal(retry.cell_updates[1].cell_count, 16)
    Assert.truthy(retry.glyph_update ~= nil)
    Assert.truthy(retry.atlas_update ~= nil)
    prepared:commit_model(retry)
    Assert.equal(state.damage.dirty_count, 0)
    prepared:destroy()
    font:destroy()
  end,
}
