local Assert = require("tests.assert")
local Terminal = require("kiwi.session.terminal")
local Transaction = require("kiwi.terminal.state_transaction")
local Vi = require("kiwi.input.vi")

local function fixture(text, columns, rows, history)
  local terminal = Terminal.new({ columns = columns or 20, rows = rows or 3,
    state_options = { scrollback_limit = history or 2000 } })
  terminal:write(text)
  local state = Terminal.state(terminal)
  state:vi_toggle(); state.vi:motion(state, "top"); state.vi:motion(state, "first")
  return state, terminal
end
local function finish(state, budget)
  local ticks = 0
  while state:vi_pending() do
    state:vi_step(budget or 13)
    Assert.truthy(state.vi.last_step_work <= (budget or 13))
    ticks = ticks + 1; assert(ticks < 100000)
  end
end
local function move(state, motion, count, argument)
  state.vi:motion(state, motion, count, argument); finish(state)
  return state:vi_view()
end

return {
  vi_line_and_word_selections_cross_only_soft_wraps = function()
    local state = fixture("abcdefghijk\r\nend", 5, 4)
    move(state, "down"); move(state, "right", 2)
    state.vi:toggle_selection(state, "line"); finish(state)
    Assert.equal(state:selection_text(100), "abcdefghijk")
    state.vi:toggle_selection(state, "word"); finish(state)
    Assert.equal(state:selection_text(100), "abcdefghijk")
    move(state, "bottom"); move(state, "first")
    Assert.equal(state:selection_text(100), "abcdefghijk\nend")
  end,
  vi_selection_expansion_yields_and_cancels_without_exposing_partial_copy = function()
    local state, terminal = fixture(string.rep("a", 6000), 100, 70)
    state.vi:toggle_selection(state, "word")
    Assert.truthy(state:vi_pending()); Assert.truthy(state.vi.last_step_work <= 256)
    Assert.equal(state:selection_view().active, false)
    local transaction = Transaction.new(state, { columns = 100, rows = 70 })
    finish(transaction.state, 19)
    Assert.equal(#transaction.state:selection_text(10000), 6000)
    Assert.truthy(state:vi_pending())
    terminal:write("b"); state:vi_step(19)
    Assert.equal(state:vi_pending(), false)
    Assert.equal(state:vi_view().status, "output-changed")
    Assert.equal(state:selection_view().active, false)
    state.vi:toggle_selection(state, "word")
    state.vi:toggle_selection(state, "word")
    Assert.truthy(state:vi_pending()); state.vi:cancel(state)
    Assert.equal(state:vi_pending(), false)
  end,
  vi_words_do_not_join_across_hard_line_breaks = function()
    local state = fixture("abcde\r\nfghij", 5, 3)
    Assert.equal(move(state, "word-end").row_index, 1)
    Assert.equal(state:vi_view().column, 4)
    Assert.equal(move(state, "word-next").row_index, 2)
    Assert.equal(state:vi_view().column, 0)
    move(state, "right", 4)
    Assert.equal(move(state, "word-back").row_index, 2)
    Assert.equal(state:vi_view().column, 0)
  end,
  vi_cursor_is_independent_and_crosses_soft_wraps_as_whole_graphemes = function()
    local state = fixture("A中éZmore", 5, 3)
    local column, row = state.cursor.column, state.cursor.row
    Assert.equal(move(state, "right").column, 1)
    Assert.equal(move(state, "right").column, 3)
    Assert.equal(move(state, "right").column, 4)
    local wrapped = move(state, "right")
    Assert.equal(wrapped.column, 0); Assert.equal(wrapped.row_index, 2)
    Assert.equal(move(state, "left").column, 4)
    Assert.equal(state.cursor.column, column); Assert.equal(state.cursor.row, row)
    Assert.equal(state:pop_responses()[1], nil)
  end,
  vi_word_motions_counts_and_unicode_whitespace_are_deterministic = function()
    local state = fixture("one,two 中é\r\n next", 20, 3)
    Assert.equal(move(state, "word-next").column, 3)
    Assert.equal(move(state, "word-next").column, 4)
    Assert.equal(move(state, "word-end").column, 6)
    Assert.equal(move(state, "word-next").column, 8)
    Assert.equal(move(state, "word-end").column, 10)
    Assert.equal(move(state, "word-back", 2).column, 4)
    move(state, "first")
    Assert.equal(move(state, "word-next", 1, "big").column, 8)
    Assert.equal(move(state, "word-next").row_index, 2)
    Assert.equal(state:vi_view().column, 1)
  end,
  vi_vertical_motions_preserve_preferred_column_and_reveal_history = function()
    local state = fixture("12345\r\n中abc\r\nthird\r\nfourth\r\nfifth", 8, 2)
    move(state, "right", 1)
    Assert.equal(move(state, "down").column, 0)
    Assert.equal(move(state, "down").column, 1)
    Assert.truthy(state.history_offset > 0)
    local bottom = move(state, "bottom")
    Assert.equal(bottom.row, 1); Assert.equal(state.history_offset, 0)
    local top = move(state, "top")
    Assert.equal(top.row, 0); Assert.equal(state.history_offset, state.scrollback:size())
  end,
  vi_visual_character_line_word_and_block_copy_preserve_cell_boundaries = function()
    local state = fixture("a中de\r\n12345\r\nxy z", 8, 3)
    move(state, "right")
    state.vi:toggle_selection(state, "character")
    Assert.equal(state:selection_text(100), "中")
    move(state, "right", 2)
    Assert.equal(state:selection_text(100), "中de")
    state.vi:toggle_selection(state, "line")
    Assert.equal(state:selection_text(100), "a中de")
    state.vi:cancel(state); move(state, "first"); move(state, "down")
    move(state, "right", 2); state.vi:toggle_selection(state, "block")
    move(state, "up"); move(state, "right")
    Assert.equal(state:selection_text(100), "中d\n34")
    state.vi:cancel(state); move(state, "bottom"); move(state, "first")
    state.vi:toggle_selection(state, "word")
    Assert.equal(state:selection_text(100), "xy")
  end,
  vi_bracket_and_inline_search_are_bounded_and_repeatable = function()
    local state = fixture("a(b(c)d)e a中b中c", 30, 2)
    Assert.equal(move(state, "bracket").column, 7)
    Assert.equal(move(state, "bracket").column, 1)
    state.vi:inline(state, "中", 1, false); finish(state)
    Assert.equal(state:vi_view().column, 11)
    state.vi:inline(state, "中", 1, true); finish(state)
    Assert.equal(state:vi_view().column, 13)
    state.vi:inline(state, "中", 1, true, nil, true); finish(state)
    Assert.equal(state:vi_view().status, "not-found")
  end,
  vi_jobs_cancel_on_output_and_can_be_copied_transactionally = function()
    local state, terminal = fixture(string.rep("a", 6000), 100, 70)
    state.vi:motion(state, "word-end")
    Assert.truthy(state:vi_pending())
    local work = state.vi.job.work
    local transaction = Transaction.new(state, { columns = state.columns, rows = state.rows })
    finish(transaction.state, 127)
    Assert.equal(transaction.state:vi_view().row_index, 60)
    Assert.equal(transaction.state:vi_view().column, 99)
    Assert.equal(state.vi.job.work, work)
    transaction:seal(); transaction:commit()
    move(state, "top"); move(state, "first"); state.vi:motion(state, "word-end")
    terminal:write("b")
    state:vi_step()
    Assert.equal(state:vi_pending(), false); Assert.equal(state:vi_view().status, "output-changed")
    Assert.equal(state:vi_view().column, 0)
  end,
  vi_reconciles_eviction_reflow_and_alternate_screen_changes = function()
    local state, terminal = fixture("abcde\r\nnext\r\nlast", 5, 2, 1)
    state.vi:toggle_selection(state, "character")
    terminal:write("\r\nnew")
    Assert.equal(state:vi_view().status, "selection-evicted")
    Assert.equal(state:vi_view().row_index, 1)
    state:vi_toggle(); state:vi_toggle(); move(state, "top"); move(state, "first"); move(state, "right", 2)
    local id = state:vi_view().line_id
    terminal:resize(3, 6)
    Assert.truthy(state:vi_view().active)
    Assert.equal(state:vi_view().column, 2)
    Assert.equal(state:vi_view().line_id, id)
    terminal:write("\27[?1049h")
    Assert.equal(state:vi_view().active, false)
  end,
}
