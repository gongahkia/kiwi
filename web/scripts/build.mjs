import { spawnSync } from 'node:child_process';
import { cp, mkdir, rm, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const web = fileURLToPath(new URL('..', import.meta.url));
const root = path.resolve(web, '..');
const build = path.join(root, 'build', 'web');
const dist = path.join(web, 'dist');
const env = { ...process.env };
if (env.EMSDK) env.PATH = `${path.join(env.EMSDK, 'upstream', 'emscripten')}${path.delimiter}${env.PATH}`;

function run(program, args) {
  const result = spawnSync(program, args, { cwd: root, env, stdio: 'inherit' });
  if (result.error) {
    console.error(`Unable to run ${program}: ${result.error.message}\nInstall and activate Emscripten 4.0.23 first. See docs/photobooth.md.`);
    process.exit(1);
  }
  if (result.status !== 0) process.exit(result.status || 1);
}

if (!process.argv.includes('--skip-wasm')) {
  run('emcmake', ['cmake', '-S', web, '-B', build, '-DCMAKE_BUILD_TYPE=Release']);
  run('cmake', ['--build', build, '--parallel', process.env.CMAKE_BUILD_PARALLEL_LEVEL || '2']);
}
try { await access(path.join(build, 'wasm', 'strok.wasm')); }
catch { console.error('The compiled renderer is missing. Run npm run build with Emscripten activated.'); process.exit(1); }

// dist is exclusively generated by this script; native and SDK outputs are separate.
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
await Promise.all([
  cp(path.join(web, 'index.html'), path.join(dist, 'index.html')),
  cp(path.join(web, 'src'), path.join(dist, 'src'), { recursive: true, filter: source => !source.endsWith('.cpp') }),
  cp(path.join(web, 'assets'), path.join(dist, 'assets'), { recursive: true }),
  cp(path.join(build, 'wasm'), path.join(dist, 'wasm'), { recursive: true }),
  writeFile(path.join(dist, '.nojekyll'), ''),
]);
console.log(`\nPhotobooth built: ${dist}\nPreview: npm --prefix web run dev`);
